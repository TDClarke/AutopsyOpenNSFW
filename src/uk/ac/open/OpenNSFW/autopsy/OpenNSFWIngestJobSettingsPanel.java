    private void customizeComponents(OpenNSFWIngestJobSettings settings) {
        skipKnownFilesCheckBox.setSelected(settings.skipKnownFiles());
        useThumbnailCheckBox.setSelected(settings.useThumbnail());
        // The spinner model is Integer-based, so clamp and set an int.
        long min = Math.max(0L, Math.min(settings.minSizeFiles(), Integer.MAX_VALUE));
        imageBytesjSpinner.setValue((int) min);
        thresholdjSpinner.setValue(Math.max(0, Math.min(100, settings.threshold())));
    }

    @Override
    public IngestModuleIngestJobSettings getSettings() {
        commitSpinner(imageBytesjSpinner);
        commitSpinner(thresholdjSpinner);
        return new OpenNSFWIngestJobSettings(
                skipKnownFilesCheckBox.isSelected(),
                useThumbnailCheckBox.isSelected(),
                ((Number) imageBytesjSpinner.getValue()).longValue(),
                ((Number) thresholdjSpinner.getValue()).intValue());
    }

    /**
     * Commits text typed into a spinner; if it isn't a valid number, the
     * editor reverts to the last valid value instead of using the bad text.
     */
    private static void commitSpinner(javax.swing.JSpinner spinner) {
        try {
            spinner.commitEdit();
        } catch (java.text.ParseException ex) {
            spinner.setValue(spinner.getValue());
        }
    }

